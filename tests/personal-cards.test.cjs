const test = require('node:test'), assert = require('node:assert/strict');
const { DatabaseSync } = require('node:sqlite');
const { createGameProfile } = require('../ops/bot-config/webGameProfile.cjs');
const { fixture, ids } = require('./helpers.cjs');
const { createBotConfigFixture, guildId } = require('./bot-config-fixture.cjs');
test('collection reads are actor and guild scoped, independent of One Piece and do not mutate data', t => {
  const db = new DatabaseSync(':memory:'); t.after(() => db.close());
  db.exec('CREATE TABLE players(guild_id TEXT,user_id TEXT); CREATE TABLE arcade_cards(guild_id TEXT,user_id TEXT,card_id TEXT,quantity INTEGER)');
  const insert = db.prepare('INSERT INTO arcade_cards VALUES(?,?,?,?)');
  insert.run(guildId, ids.USER, 'WN-001', 3); insert.run(guildId, ids.ADMIN, 'WN-002', 8);
  insert.run(ids.OWNER, ids.USER, 'WN-003', 10); insert.run(guildId, ids.USER, 'WN-004', 0);
  const reader = createGameProfile({ db, isGameAdminMember: () => false }, {});
  const result = reader(guildId, ids.USER, 'normal');
  assert.equal(result.player, null);
  assert.deepEqual(result.collection, { available: true, cards: [{ id: 'WN-001', quantity: 3 }] });
  assert.equal(db.prepare('SELECT count(*) n FROM players').get().n, 0);
  assert.equal(db.prepare('SELECT sum(quantity) n FROM arcade_cards').get().n, 21);
});
test('personal collection page requires login and uses only the session actor', async t => {
  const bots = createBotConfigFixture(ids), f = fixture({ botTransport: bots.transport });
  t.after(() => f.close()); await f.listen();
  const preview = await f.request('/profile/cards');
  assert.equal(preview.status, 200);
  const previewHtml = await preview.text();
  assert.match(previewHtml, /og:image/);
  assert.match(previewHtml, /Ouvrir ma collection avec Discord/);
  assert.doesNotMatch(previewHtml, /personal-cards\.js/);
  const image = await f.request('/profile/cards?preview=share');
  assert.equal(image.status, 200);
  assert.match(image.headers.get('content-type'), /image\/png/);
  assert.equal((await f.request('/profile/cards?guild=' + guildId)).status, 200);
  const { nextPath } = require('../server/security.cjs');
  assert.equal(nextPath('/profile/cards?guild=' + guildId), '/profile/cards?guild=' + guildId);
  assert.equal(nextPath('/profile/cards?user=' + ids.ADMIN), '/profile');
  assert.equal((await f.request('/api/platform/me/game/' + guildId)).status, 401);
  const login = await f.login('USER');
  const page = await f.request('/profile/cards', login); assert.equal(page.status, 200);
  const html = await page.text(); assert.match(html, /personal-cards.js/); assert.match(html, /catalogue.js/);
  await f.request('/api/platform/me/game/' + guildId + '?actor=' + ids.ADMIN, login);
  assert.equal(bots.calls.at(-1).options.headers['x-wn-actor'], ids.USER);
});
